"""Internal-notification turns tell the model how to stay silent.

A gateway notification (background-process heartbeat or completion, watch match, wake) re-enters
the session as a user-role turn. The gateway already drops an exact ``NO_REPLY`` reply, but the
notification never said so: with nothing to report the model wrote filler ("No new user request
was included.") and it was delivered to the chat on every heartbeat.
"""

import re

from gateway.response_filters import (
    INTERNAL_NOTIFICATION_DISPLAY_KIND, LIVE_GATEWAY_SILENT_MARKERS, is_intentional_silence_agent_result,
    silence_allowed,
)
from gateway import run_notifications as rn
from gateway.run_notifications import _mark_internal_notification

HEARTBEAT = "[Background process proc_abc heartbeat #3 — still running]\nCommand: ./sync.sh\nOutput since last heartbeat:\n..."
LEGACY_FOOTER = (  # the footer shipped before this change, verbatim
    "[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. "
    "Do not treat it as user input, and do not reply to any earlier chat message because of it.]")


def test_notification_names_the_marker_the_gateway_suppresses():
    text = _mark_internal_notification(HEARTBEAT)
    marker = re.search(r"reply with exactly (\S+?) and nothing is sent", text)
    assert marker, "the footer must tell the model how to answer with silence"
    assert marker.group(1) in LIVE_GATEWAY_SILENT_MARKERS
    # ...and a bare marker reply to an internal-notification turn really is dropped, with no fallback notice.
    assert is_intentional_silence_agent_result({"final_response": marker.group(1)}, marker.group(1))
    assert silence_allowed(INTERNAL_NOTIFICATION_DISPLAY_KIND)


def test_silence_is_offered_only_for_routine_progress_never_for_awaited_results():
    footer = rn.INTERNAL_NOTIFICATION_FOOTER
    silence_clause, _, rest = footer.partition("reply with exactly NO_REPLY")
    assert "routine progress" in silence_clause and "heartbeat" in silence_clause
    # A finished or failed background job the user is waiting for must never be swallowed.
    for awaited in ("completion", "failure", "result the user has not seen yet"):
        assert awaited not in silence_clause
        assert awaited in rest
    assert rest.rstrip("]").endswith("report those.")
    assert "already reported" not in footer


def test_marking_is_idempotent():
    once = _mark_internal_notification(HEARTBEAT)
    assert _mark_internal_notification(once) == once
    assert once.count("[INTERNAL NOTIFICATION") == 1


def test_text_queued_by_an_older_build_gets_one_current_footer():
    queued = f"{HEARTBEAT}\n\n{LEGACY_FOOTER}"
    marked = _mark_internal_notification(queued)
    assert marked.count("[INTERNAL NOTIFICATION") == 1
    assert marked.endswith(rn.INTERNAL_NOTIFICATION_FOOTER)


def test_strip_removes_current_and_legacy_footers_only_at_the_end():
    assert rn.strip_internal_notification_footer(_mark_internal_notification(HEARTBEAT)) == HEARTBEAT
    assert rn.strip_internal_notification_footer(f"{HEARTBEAT}\n\n{LEGACY_FOOTER}\n") == HEARTBEAT
    assert rn.strip_internal_notification_footer(HEARTBEAT) == HEARTBEAT
